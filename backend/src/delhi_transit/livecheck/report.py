"""Writers for reports/live-check-<day>.{md,csv,json}."""
from __future__ import annotations

import csv
import io
from datetime import datetime
from pathlib import Path
from typing import Any

from delhi_transit.core.config import portable_path
from delhi_transit.core.io import atomic_write_json, atomic_write_text
from delhi_transit.livecheck.analyze import SMALL_SAMPLE

PATH_KEYS = frozenset({"file", "path", "passages_path"})


def _portable_paths(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            key: portable_path(item) if key in PATH_KEYS and isinstance(item, str) else _portable_paths(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [_portable_paths(item) for item in value]
    return value


LEG_COLUMNS = (
    "slot", "query_id", "requested_at_iso", "option_index", "route_id", "from_stop_id", "from_stop",
    "to_stop_id", "to_stop", "predicted_board_ts", "stop_arrival_ts", "timing_source",
    "observed_coverage", "feed_age_seconds", "scheduled_s", "predicted_s", "p10_s", "p90_s",
    "matched", "unmatched_reason", "actual_vehicle_id", "actual_run_id", "actual_board_ts",
    "board_delay_s", "actual_s", "error_s", "in_p10_p90", "observed_only",
)


def _fmt(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(_fmt(cell) for cell in row) + " |" for row in rows]
    return lines


def _accuracy_rows(groups: dict[str, dict[str, Any]]) -> list[list[Any]]:
    return [
        [
            name,
            stats.get("count"),
            stats.get("mae_s"),
            stats.get("bias_s"),
            stats.get("median_ae_s"),
            stats.get("timetable_mae_s"),
            f"{stats['p10_p90_coverage']:.1%}" if stats.get("count") else None,
            "yes" if stats.get("small_sample") else ("no" if stats.get("count") else None),
        ]
        for name, stats in groups.items()
    ]


ACCURACY_HEADERS = ["stratum", "legs", "MAE s", "bias s", "median AE s", "timetable MAE s", "[p10, p90] coverage", "small sample"]


def _limitations(result: dict[str, Any]) -> list[str]:
    window, acc = result.get("window") or {}, result["accuracy"]
    if not window:
        return []
    lines = [
        "## Window and limitations",
        "",
        (f"- Recorded window: {window['first_ok']} to {window['last_ok']} (first to last successful poll, "
         f"{window['minutes']} min); planned end was {result['run'].get('until')}."),
    ]
    if datetime.fromisoformat(window["first_ok"]).hour >= 20:
        lines.append("- The window starts after the evening peak, so it says nothing about peak-hour accuracy.")
    lines += [
        f"- Slot {slot}: {c['legs']} predicted 717A ride legs, {c['end_after_window']} predicted to end after the last poll "
        "(their actual ride cannot be rebuilt from this recording)."
        for slot, c in window["legs_by_slot"].items()
    ]
    if acc["legs_matched"] < SMALL_SAMPLE:
        lines.append(
            f"- Small sample: {acc['legs_matched']} matched legs of {acc['legs_total']}; the accuracy numbers below are "
            "indicative only."
        )
    return lines + [""]


def run_status_line(run: dict[str, Any]) -> str:
    if run.get("status") == "stopped_before_completion":
        return (
            "- Run status: stopped before completion; the recorder wrote no final status (`run-summary.json` "
            f"still says `{run.get('summary_status')}`). Started {run.get('started_at')}, last summary update "
            f"{run.get('updated_at')}, last successful poll {run.get('last_ok_poll')} (planned end {run.get('until')})."
        )
    return (
        f"- Run status: {run.get('status')}; started {run.get('started_at')}, last update {run.get('updated_at')} "
        f"(planned end {run.get('until')})."
    )


def render_markdown(result: dict[str, Any]) -> str:
    run, health, responses = result["run"], result["feed_health"], result["responses"]
    acc, actuals = result["accuracy"], result.get("actuals") or {}
    lines = [
        f"# Live check {result['day']}",
        "",
        ("Generated by `python -m delhi_transit.livecheck analyze` from the raw recording. "
        "Accuracy compares predicted 717A ride legs from live `/journeys` responses with ride times "
        "rebuilt from the same day's recorded GPS. Google is a comparator, not ground truth."),
        "",
    ]
    lines += _limitations(result)
    lines += [
        "## Recording",
        "",
        run_status_line(run),
        (f"- Polls: {health['polls']} attempted, {health['ok']} ok (success rate {_fmt(health['success_rate'])}); "
        f"first ok {health['first_ok']}, last ok {health['last_ok']}; repeated snapshots {health['repeated_snapshots']}."),
        f"- Poll errors: {health['errors'] or 'none'}.",
        f"- Gaps over 2 minutes between successful polls: {len(health['gaps_over_2_min'])}"
        + "".join(f"; {gap['from']} to {gap['to']} ({gap['seconds']} s)" for gap in health["gaps_over_2_min"]),
        (f"- Vehicles per poll (min/median/max): {health['vehicles'].get('min')}/{health['vehicles'].get('median')}/"
        f"{health['vehicles'].get('max')}; feed age at poll (s): {health['feed_age_at_poll_s'].get('min')}/"
        f"{health['feed_age_at_poll_s'].get('median')}/{health['feed_age_at_poll_s'].get('max')}."),
        "",
        "## Scheduled live journeys",
        "",
        (f"- {len(result['slots'])} slots every {_fmt(run.get('slot_minutes'))} min until {run.get('journeys_until')}; "
        f"{responses['responses']} responses saved."),
        f"- By status: {responses['by_status']}; abstention reason codes: {responses['by_reason_code'] or 'none'}.",
        (f"- Feed age at request (s, min/median/max): {responses['feed_age_s'].get('min')}/"
        f"{responses['feed_age_s'].get('median')}/{responses['feed_age_s'].get('max')} "
        f"(threshold {_fmt(responses['stale_threshold_s'])} s)."),
        (f"- Rule checks: ok responses not in live mode {responses['ok_not_live_mode']}, ok responses with a stale feed "
        f"{responses['ok_with_stale_feed']}, ride legs missing provenance/coverage/window "
        f"{responses['ok_ride_legs_missing_fields']}, abstentions without a reason code "
        f"{responses['abstentions_without_code']}."),
        "",
    ]
    lines += _table(
        ["slot", "started", "queries", "statuses", "feed age at slot start s"],
        [[s["slot"], s["started_at"], s["queries"], s["statuses"], s.get("feed_age_at_slot_start_s")] for s in result["slots"]],
    )
    lines += ["", "## Actual 717A runs from today's GPS", ""]
    if actuals:
        gps = actuals.get("gps", {})
        lines.append(
            f"- {gps.get('snapshots')} snapshots, {gps.get('raw_rows')} position rows, {gps.get('clean_rows')} after "
            f"first-copy dedupe on (vehicle_id, ts, lat, lng); matcher radius {actuals.get('radius_m')} m."
        )
        lines.append(f"- {actuals.get('runs')} runs reconstructed, {actuals.get('excluded_runs')} excluded." + (f" Note: {actuals['note']}" if actuals.get("note") else ""))
        lines += [""] + _table(
            ["direction", "route", "runs", "passages", "observed coverage"],
            [[d, v["route_id"], v["runs"], v["passages"], f"{v['observed_coverage']:.1%}"] for d, v in actuals.get("by_direction", {}).items()],
        )
    else:
        lines.append("- Actuals were not built (run `livecheck actuals` first).")
    rule = result["matching_rule"]
    lines += [
        "",
        "## Accuracy against actual ride times",
        "",
        f"Matching rule (tolerance {rule['board_tolerance_s']} s, maximum board delay {rule['max_board_delay_s']} s): "
        + " ".join(rule["text"].split()),
        "",
        (f"Predicted 717A ride legs: {acc['legs_total']}, matched {acc['legs_matched']}. "
        f"Unmatched by reason: {acc['unmatched_by_reason'] or 'none'}. Error is predicted minus actual; positive bias "
        "means the prediction was too long. Strata under 30 legs are marked as small samples and are not conclusive."),
        "",
    ]
    groups = {"all matched": acc["overall"], **{f"provenance {k}": v for k, v in acc["by_provenance"].items()},
              **{f"route {k}": v for k, v in acc["by_route"].items()}, "observed-only": acc["observed_only"],
              **{f"observed-only, {k}": v for k, v in acc["observed_only_by_provenance"].items()}}
    lines += _table(ACCURACY_HEADERS, _accuracy_rows(groups))
    google = result["google"]
    summary = google.get("summary") or {}
    lines += [
        "",
        "## Google comparison",
        "",
        (f"- Paid (uncached) calls in this run's Google log: {google.get('calls_in_log')}; ledger before the run "
        f"{summary.get('ledger_before')}; run limit {summary.get('max_calls')} calls."),
        "- Google durations are door to door for a bus-only itinerary; they are a comparator, not ground truth.",
        "",
    ]
    if google["rows"]:
        lines += _table(
            ["slot", "OD", "depart", "our total s", "our [p10, p90] s", "Google s", "Google in window", "our 717A ride s", "actual 717A ride s", "Google 717A ride s"],
            [[r["slot"], r["od_id"], r["departure_time"], r["our_total_s"], f"[{_fmt(r['our_p10_s'])}, {_fmt(r['our_p90_s'])}]",
              r["google_s"], r["google_in_our_window"], r["our_717a_ride_s"], r["actual_717a_ride_s"], r["google_717a_ride_s"]] for r in google["rows"]],
        )
    else:
        lines.append("No Google calls in this run.")
    return "\n".join(lines) + "\n"


def legs_csv(legs: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=LEG_COLUMNS, extrasaction="ignore", lineterminator="\n")
    writer.writeheader()
    for leg in legs:
        writer.writerow({key: leg.get(key) for key in LEG_COLUMNS})
    return buffer.getvalue()


def write_reports(result: dict[str, Any], report_dir: Path) -> dict[str, Path]:
    result = _portable_paths(result)
    stem = Path(report_dir) / f"live-check-{result['day']}"
    paths = {"md": stem.with_suffix(".md"), "csv": stem.with_suffix(".csv"), "json": stem.with_suffix(".json")}
    atomic_write_text(paths["md"], render_markdown(result))
    atomic_write_text(paths["csv"], legs_csv(result["legs"]))
    atomic_write_json(paths["json"], {key: value for key, value in result.items() if key != "legs"})
    return paths
